window.currentLang = localStorage.getItem('lang') || 'en';

window.applyTranslations = () => {
    document.documentElement.lang = window.currentLang;
    document.documentElement.dir = window.currentLang === 'ur' ? 'rtl' : 'ltr';

    // Update simple text elements
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[window.currentLang][key]) {
            if (el.tagName === 'INPUT' && el.type === 'text') {
                el.placeholder = translations[window.currentLang][key];
            } else if (el.tagName === 'OPTION') {
                el.textContent = translations[window.currentLang][key];
            } else {
                // If it contains a child icon, preserve the icon
                const icon = el.querySelector('svg');
                if (icon) {
                    el.innerHTML = '';
                    el.appendChild(icon);
                    el.appendChild(document.createTextNode(' ' + translations[window.currentLang][key]));
                } else {
                    el.textContent = translations[window.currentLang][key];
                }
            }
        }
    });

    // Specific button for language toggle
    document.querySelectorAll('#lang-toggle-btn').forEach(btn => {
        btn.textContent = translations[window.currentLang]['btn_urdu'];
    });
};

document.addEventListener('DOMContentLoaded', () => {
    window.applyTranslations();

    document.querySelectorAll('#lang-toggle-btn').forEach(btn => {
        btn.addEventListener('click', () => {
            window.currentLang = window.currentLang === 'en' ? 'ur' : 'en';
            localStorage.setItem('lang', window.currentLang);
            window.applyTranslations();
        });
    });
});

window.translations = translations;
